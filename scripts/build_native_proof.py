#!/usr/bin/env python3
"""Generate a bounded T05 fixture; never a runtime curriculum/release package."""
import argparse, hashlib, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'ios/ProjectBeta/ProjectBeta/Presentation/NativeProof/NativeProofData.swift'
def build():
    inputs = {}
    def read(path):
        data = (ROOT/path).read_bytes(); inputs[path] = hashlib.sha256(data).hexdigest()
        return json.loads(data)
    speech = {r['key']: r for r in read('docs/content-authoring/sentence-bank/speech.json')['records']}
    lessons = [read(f'docs/content-authoring/lesson-{n:02}.json') for n in [1,5,10,16,26,50]]
    read('docs/content-authoring/sentence-bank/bound-contexts.json')
    review = json.loads((ROOT/'docs/content-authoring/sentence-bank/validation-report.json').read_bytes())
    assert review['task_authoring_acceptance_complete'], 'T04 authoring review is incomplete'
    for path, pin in inputs.items():
        assert review['input_and_validator_sha256'].get(path) == pin, 'Stale T04 handoff: '+path
    rows = []
    def row(key, japanese, meaning, label):
        record = speech[key]
        assert record['status'] == 'reviewed'
        return dict(id=key, segments=japanese['segments'], meaning=meaning, label=label,
                    speech=record['speech_text'], speechRecordID=record['id'], sourceHash=record['source_sha256'])
    for lesson in lessons:
        for entry in lesson['vocabulary']:
            bases = ''.join(s['base'] for f in entry['forms'] for s in f['japanese']['segments'])
            if entry['editorial_key'] in ['person_over_there','name_honorific'] or any(x in bases for x in ['JR','ATM']) or (lesson['reference_lesson_number'] in [1,5,26,50] and any(x in bases for x in ['～','〜'])):
                for form in entry['forms']:
                    key = f"vocabulary:{entry['id']}:{form['key']}"
                    meanings = [m['text']['en'] for m in entry['meanings'] if form['key'] in m['form_keys']]
                    item = row(key, form['japanese'], '; '.join(meanings), f"{lesson['source_level_label']} · {lesson['reference_lesson_number']} · {form['key']}")
                    if speech[key]['source'] == 'bound_context': item['label'] += ' · Context: '+speech[key]['speech_text']
                    rows.append(item)
    # Longest reviewed original example in each representative lesson; no new text.
    for lesson in lessons:
        ex = max(lesson['examples'],key=lambda e:len(''.join(s['base'] for s in e['japanese']['segments'])))
        rows.append(row('example:'+ex['id'],ex['japanese'],ex['translation']['en'],f"{lesson['source_level_label']} · {lesson['reference_lesson_number']}"))
    dialogue = lessons[0]['dialogues'][0]
    turns = [row(f"dialogue:{dialogue['id']}:turn:{i}",t['japanese'],t['translation']['en'],t['speaker_key']) for i,t in enumerate(dialogue['turns'])]
    return dict(scope='T05 bounded native proof only; English fixture meanings; not release content',inputHashes=inputs,
                rows=rows,dialogueID=dialogue['id'],dialogueTitle=dialogue['title']['en'],turns=turns)
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    payload=json.dumps(build(),ensure_ascii=False,indent=2)
    text='// Generated by scripts/build_native_proof.py. Do not edit.\n#if DEBUG\nimport Foundation\nenum NativeProofData {\n    static let json = #"""\n'+payload+'\n"""#\n}\n#endif\n'
    if args.check:
        assert OUT.read_text()==text, 'Stale native proof fixture'
    else: OUT.write_text(text)
    print('T05 native fixture: current')
if __name__=='__main__': main()
